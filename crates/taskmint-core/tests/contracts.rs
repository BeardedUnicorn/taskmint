/// Every `pub const` contract.rs declares, by name.
/// contract.rs constants only Rust reads, so constants.ts leaves them out.
/// Add one here only when no TypeScript reads it (and drop it from here
/// when one starts to).
const RUST_ONLY: &[&str] = &[
    // The frontend recognizes these timer errors by their parts (CORE_ERROR_PARTS)
    "ERR_START_INACTIVE_SESSION",
    "ERR_RESUME_INACTIVE_SESSION",
    "ERR_ANOTHER_TIMER_RUNNING",
    "ERR_STOP_NOT_RUNNING",
    "ERR_PAUSE_NOT_RUNNING",
    // The capture endpoint's own reply; the extension shows whatever comes back
    "ERR_UNEXPECTED_PAYLOAD_SHAPE",
    // start_task's and apply_idle_choice's values: the generated types already
    // spell them, and TypeScript checks every use against those
    "START_OUTCOME_STARTED",
    "START_OUTCOME_RESUMED",
    "START_OUTCOME_ALREADY_RUNNING",
    "IDLE_CHOICE_DISCARD_RESUME",
    "IDLE_CHOICE_KEEP_RESUME",
    "IDLE_CHOICE_STAY_PAUSED",
    // Limits and paths only the Rust servers enforce or serve
    "HEALTH_PATH",
    "MAX_CAPTURE_BODY_BYTES",
    "MAX_ENCODED_LINK_BYTES",
];

fn contract_constant_names() -> BTreeSet<String> {
    let source = fs::read_to_string(manifest_dir().join("src/contract.rs")).unwrap();
    source
        .lines()
        .filter_map(|line| line.trim().strip_prefix("pub const "))
        .filter_map(|rest| rest.split(':').next())
        .map(str::to_string)
        .collect()
}

fn commands(cfg: &Config) -> String {
    let commands = command_types(cfg);
    let mut uses: BTreeSet<String> = commands
        .iter()
        .flat_map(|command| command.uses.iter().cloned())
        .collect();
    uses.remove("NoArgs");
    let mut out = HEADER.to_string();
    for name in &uses {
        out.push_str(&format!(
            "import type {{ {} }} from \"./{}\";\n",
            name, name
        ));
    }
    out.push_str(
        "\n/** Every command's arguments (`void` for none) and reply. */\nexport interface CommandMap {\n",
    );
    for command in &commands {
        let args = if command.args == "NoArgs" {
            "void"
        } else {
            &command.args
        };
        out.push_str(&format!(
            "  {}: {{ args: {}; reply: {} }};\n",
            command.name, args, command.reply
        ));
    }
    out.push_str(
        "}\n\nexport type CommandName = keyof CommandMap;\n\
         export type CommandArgs<K extends CommandName> = CommandMap[K][\"args\"];\n\
         export type CommandReply<K extends CommandName> = CommandMap[K][\"reply\"];\n",
    );
    out
}

/// The generated type files, by module path (`TaskSession`,
/// `serde_json/JsonValue`).
fn type_modules(dir: &Path, prefix: &str) -> Vec<String> {
    let mut modules = Vec::new();
    let mut entries: Vec<_> = fs::read_dir(dir).unwrap().map(|e| e.unwrap()).collect();
    entries.sort_by_key(|entry| entry.file_name());
    for entry in entries {
        let name = entry.file_name().into_string().unwrap();
        if entry.file_type().unwrap().is_dir() {
            modules.extend(type_modules(&entry.path(), &format!("{}{}/", prefix, name)));
        } else if let Some(stem) = name.strip_suffix(".ts") {
            modules.push(format!("{}{}", prefix, stem));
        }
    }
    modules
}

fn index(types: &[String]) -> String {
    let mut out = HEADER.to_string();
    for module in types {
        let name = module.rsplit('/').next().unwrap();
        out.push_str(&format!(
            "export type {{ {} }} from \"./{}\";\n",
            name, module
        ));
    }
    out.push_str("export type * from \"./commands\";\nexport * from \"./constants\";\n");
    out
}

#[test]
fn contracts_are_generated_from_the_rust() {
    let dir = generated_dir();
    // Start empty, so a type that's gone takes its file with it
    let _ = fs::remove_dir_all(&dir);
    let cfg = Config::new().with_large_int("number").with_out_dir(&dir);

    export_types(&cfg);
    let types = type_modules(&dir, "");
    let constants = constants();
    fs::write(dir.join("constants.ts"), &constants.text).unwrap();
    fs::write(dir.join("commands.ts"), commands(&cfg)).unwrap();
    fs::write(dir.join("index.ts"), index(&types)).unwrap();

    // Every type a command names was exported
    for command in command_types(&cfg) {
        for name in command.uses.iter().filter(|name| *name != "NoArgs") {
            assert!(
                types.contains(name),
                "{} uses {}, which isn't exported",
                command.name,
                name
            );
        }
    }
    // Every contract constant is in constants.ts, unless only Rust reads it
    let missing: Vec<String> = contract_constant_names()
        .into_iter()
        .filter(|name| !constants.used.contains(name.as_str()))
        .filter(|name| !RUST_ONLY.contains(&name.as_str()))
        .collect();
    assert!(
        missing.is_empty(),
        "contract.rs constants missing from constants.ts: {:?}",
        missing
    );
}
