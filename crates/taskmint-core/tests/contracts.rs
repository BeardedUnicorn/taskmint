//! Writes packages/contracts/src/generated from the Rust: the wire types
//! (ts-rs), each command's argument and reply types (`CommandMap`), and the
//! constants in contract.rs. scripts/verify.sh runs it and fails when git
//! then sees a change, so the TypeScript can't drift from the Rust:
//!
//!     cargo test -p taskmint-core --features ts --test contracts
// Writing files is this test's job; core's own code stays free of I/O.
