const HEADER: &str = "// Generated by crates/taskmint-core/tests/contracts.rs from the Rust. Don't edit:\n\
                      // change the Rust, then run `cargo test -p taskmint-core --features ts --test contracts`.\n";

fn manifest_dir() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
}

fn generated_dir() -> PathBuf {
    manifest_dir().join("../../packages/contracts/src/generated")
}

/// Exports each type, and the types it's built from.
macro_rules! export {
    ($cfg:expr, $($ty:ty),* $(,)?) => {
        $( <$ty as TS>::export_all($cfg).expect(stringify!($ty)); )*
    };
}

