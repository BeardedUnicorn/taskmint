/// A `export const NAME = { KEY: value, ... } as const;` block, recording
/// which contract.rs constants it used.
struct Constants {
    text: String,
    used: BTreeSet<&'static str>,
}

impl Constants {
    fn group(&mut self, doc: &str, name: &str, entries: &[(&'static str, &str, Value)]) {
        self.text
            .push_str(&format!("\n/** {} */\nexport const {} = {{\n", doc, name));
        for (rust, key, value) in entries {
            self.used.insert(rust);
            self.text.push_str(&format!("  {}: {},\n", key, value));
        }
        self.text.push_str("} as const;\n");
    }

    fn line(&mut self, text: &str) {
        self.text.push_str(text);
    }

    fn value(&mut self, doc: &str, rust: &'static str, value: Value) {
        self.used.insert(rust);
        self.text.push_str(&format!(
            "\n/** {} */\nexport const {} = {};\n",
            doc, rust, value
        ));
    }

    fn list(&mut self, doc: &str, rust: &'static str, name: &str, items: &[&str]) {
        self.used.insert(rust);
        let items: Vec<String> = items.iter().map(|item| json!(item).to_string()).collect();
        self.text.push_str(&format!(
            "\n/** {} */\nexport const {} = [\n  {},\n] as const;\n",
            doc,
            name,
            items.join(",\n  ")
        ));
    }
}

